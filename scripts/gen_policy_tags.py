"""Generate data/policies/policy_tags.yaml: policy id -> the agent tools the policy applies to ("applies to").

The only field taken from data/policies/policy_logic.yaml is `actions` (which tools a rule governs, as a real
policy store records next to each rule). Condition, fact, decision and risk type are never read, so the tags say
nothing about how a case is decided. Used by the v2 retriever (src/monitor/case_inputs.py) to look only at the
policies for the proposed action's tool. The tags are to be confirmed by a person from the visible policy text
(decisions.md, 2026-11-11 row); tests/test_policy_tags.py fails when the file is out of date.

Run:  python scripts/gen_policy_tags.py
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
LOGIC = ROOT / "data" / "policies" / "policy_logic.yaml"
OUT = ROOT / "data" / "policies" / "policy_tags.yaml"
HEADER = """# GENERATED by scripts/gen_policy_tags.py from the `actions` field of policy_logic.yaml. Do not edit by hand.
# policy id -> the agent tools the policy applies to. Metadata for the v2 retriever (src/policies/retriever.py):
# it says which tools a rule governs, never its condition, fact or decision. In-domain and OOD stores share ids.
"""


def build() -> str:
    logic = yaml.safe_load(LOGIC.read_text(encoding="utf-8"))
    tags = {pid: sorted(set(entry.get("actions") or [])) for pid, entry in sorted(logic.items())}
    return HEADER + yaml.safe_dump(tags, sort_keys=True, default_flow_style=None, width=120)


def main() -> int:
    OUT.write_text(build(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
