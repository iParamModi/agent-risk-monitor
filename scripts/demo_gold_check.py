"""Hand-written `expected` of each demo task next to the decision the policy store gives on the true state.

    python scripts/demo_gold_check.py            # reads outputs/live/demo, writes docs/reports/demo_gold_check.md

CPU only, no model. For each demo task (lma_agent/tasks/demo_tasks.yaml) it takes the recorded `always` run, because
that run holds every check result of the action's table, and builds the true facts of the judged resource:
its record in the run's company_snapshot plus the gateway check results. Then every rule of
data/policies/policy_logic.yaml that lists the action is evaluated with the evaluator of
scripts/check_tool_coverage.py (`evaluate`, the "gold from policies" code that checks the seeds), and the
strictest rule that fires is the decision (decisions.md: BLOCK > ASK_CONFIRMATION > ALLOW). Every true fact is
bound, so a condition over two facts (P_REPO_15) is decided too; the seed checker binds one fact per rule. Rules whose fact is
not in the state, and rules that read the action text ("violation visible"), are listed as not evaluated.
src/policies/gold_engine.py and src/data_gen/labeler.py are empty stubs, so this evaluator is the only gold
logic in the repo.

Nothing here changes a log, a task or a label: it only reports.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from lma_agent.tasks.load_tasks import load_tasks  # noqa: E402
from scripts import check_tool_coverage as ctc  # noqa: E402

RUNS = ROOT / "outputs" / "live" / "demo"
OUT = ROOT / "docs" / "reports" / "demo_gold_check.md"
TASKS = ROOT / "lma_agent" / "tasks" / "demo_tasks.yaml"
STORES = {"delete_file": ("files", "file"), "delete_repository": ("repos", "repo")}


def read_log(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def first(events: list[dict], kind: str) -> dict:
    return next(e["payload"] for e in events if e["type"] == kind)


def true_facts(events: list[dict]) -> tuple[dict, dict, dict]:
    """(action, facts of the judged resource, context) from one always run."""
    action = first(events, "risk_action")
    state = first(events, "company_snapshot")["state"]
    store, arg = STORES[action["tool"]]
    facts = {k: v for k, v in state[store][action["args"][arg]].items() if not isinstance(v, (dict, list))}
    for e in events:
        if e["type"] == "gateway_check" and isinstance(e["payload"]["result"], dict):
            facts.update({k: v for k, v in e["payload"]["result"].items() if k not in e["payload"]["args"]})
    who = state["current_user"]
    team = (state["users"].get(who) or {}).get("team")
    return action, facts, {"requested_by": who, "requester_team": team}


def judge(action: dict, facts: dict, context: dict) -> tuple[str, list[dict]]:
    """(strictest decision of the rules that fire, one row per rule that lists the action)."""
    rows, fired = [], []
    for pid, rule in ctc.LOGIC.items():
        if action["tool"] not in rule["actions"]:
            continue
        kind = ctc.condition_kind(rule)
        if kind == "always":
            result = "always allowed (restricts nothing)"
        elif kind != "expr":
            result = "not evaluated (reads the action text)"
        else:
            try:
                value = ctc.evaluate(rule, facts, action["args"], {**facts, **context}, pid)   # every true fact bound
            except ctc.UnboundName as err:
                value, result = None, f"not evaluated ({err})"
            if value is True:
                result = "FIRES"
                fired.append(rule["decision"])
            elif value is False:
                result = "does not fire"
            elif not isinstance(value, bool) and rule.get("fact") not in facts:
                result = f"not evaluated (`{rule.get('fact')}` is not a fact of this record)"
            elif value is None:
                result = "not evaluated"
        rows.append({"policy": pid, "decision": rule["decision"], "condition": rule["condition"], "result": result})
    return (ctc.strictest(fired) if fired else "ALLOW"), rows


def conflicts(pids: list[str], tool: str) -> list[str]:
    return [" + ".join(c["policies"]) for c in ctc.CONFLICTS
            if c.get("action") == tool and set(c["policies"]) <= set(pids)]


def runs_of(task_id: str, summary: list[dict]) -> list[dict]:
    return [r for r in summary if r["task"] == task_id]


def report(folder: Path) -> str:
    summary = json.loads((folder / "summary.json").read_text(encoding="utf-8"))
    lines = ["# Demo tasks: hand-written `expected` vs the policy store", "",
             "Generated by `python scripts/demo_gold_check.py` from the recorded runs in `outputs/live/demo/`, "
             "`data/policies/policy_logic.yaml` and `conflicts.yaml`. Do not edit by hand.", ""]
    head = ["task", "action", "hand-written expected", "policy store on the true state", "same", "rules that fire"]
    table, details = [head, ["---"] * len(head)], []
    for task in load_tasks(TASKS):
        rows = runs_of(task.task_id, summary)
        always = next((r for r in rows if r["setting"] == "always"), None)
        if always is None:
            table.append([task.task_id, "-", task.expected["decision"], "no always run recorded", "-", "-"])
            continue
        events = read_log(folder / always["file"])
        action, facts, context = true_facts(events)
        gold, rules = judge(action, facts, context)
        fire = [r for r in rules if r["result"] == "FIRES"]
        call = f"`{action['tool']}({json.dumps(action['args'])})`"
        table.append([task.title or task.task_id, call, task.expected["decision"], gold,
                      "yes" if gold == task.expected["decision"] else "**no**",
                      ", ".join(f"{r['policy']} ({r['decision']})" for r in fire) or "none"])
        details += ["", f"## {task.title or task.task_id}", "",
                    f"Action {call}, asked by `{context['requested_by']}` (team `{context['requester_team']}`). "
                    f"True facts of the resource: " + ", ".join(f"`{k} = {json.dumps(v)}`" for k, v in sorted(facts.items()))
                    + ".", ""]
        clash = conflicts([r["policy"] for r in fire], action["tool"])
        if clash:
            details += [f"Listed in `conflicts.yaml` for this action: {'; '.join(clash)} (decisions.md: ESCALATE).", ""]
        details += ["| policy | rule decision | condition | on the true state |", "|---|---|---|---|"]
        details += [f"| {r['policy']} | {r['decision']} | `{r['condition']}` | {r['result']} |" for r in rules]
        details += ["", "| run | policies retrieved (k=8) | firing rules among them | monitor decision | policy cited |",
                    "|---|---|---|---|---|"]
        for run in rows:
            ev = read_log(folder / run["file"])
            shown = [p["policy_id"] for p in first(ev, "policies")["policies"]]
            d = first(ev, "decision")
            twice = sum(r["setting"] == run["setting"] for r in rows) > 1
            name = run["setting"] + (f", answer {run['confirm']}" if twice else "")
            details.append(f"| {name} | {', '.join(sorted(shown))} | "
                           f"{', '.join(r['policy'] for r in fire if r['policy'] in shown) or 'none'} | "
                           f"{d['decision']} | {', '.join(d['policy_ids']) or '-'} |")
    lines += ["| " + " | ".join(r) + " |" for r in table]
    return "\n".join(lines + details) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--runs", default=str(RUNS))
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args(argv)
    text = report(Path(args.runs))
    Path(args.out).write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
